const DICTS: Record<UiLang, Partial<Dict>> = { en, de, fr, zh };

export function translator(lang: UiLang) {
  const d = DICTS[lang] ?? en;
  return (key: MessageKey, vars?: Record<string, string>) => {
    let s = d[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
}

export type T = ReturnType<typeof translator>;

export const UI_LANG_NAMES: Record<UiLang, string> = { en: 'English', de: 'Deutsch', fr: 'Français', zh: '中文' };

export function missingKeys(lang: UiLang): MessageKey[] {
  return (Object.keys(en) as MessageKey[]).filter((k) => k !== 'appName' && !(k in DICTS[lang]));
}
